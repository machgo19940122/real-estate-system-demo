function estimateItemToCalcForm(item: EstimateItem) {
  const kind = item.line_kind ?? "general";
  return normalizeEstimateLineItem({
    id: item.id,
    line_kind: kind,
    name: item.name,
    quantity: item.quantity,
    unit: item.unit ?? DEFAULT_ESTIMATE_UNIT,
    unit_price: item.unit_price,
    direct_amount:
      kind === "discount" || kind === "subtotal" ? item.amount : 0,
  });
}

/** 明細から見積ヘッダの税抜・税・合計を算出 */
export function getEst010DemoTotals(): {
  subtotal: number;
  tax: number;
  total: number;
} {
  const subtotal = calcEstimateTaxableSubtotal(
    EST010_DEMO_ITEMS.map(estimateItemToCalcForm)
  );
  const tax = Math.floor(subtotal * 0.1);
  return { subtotal, tax, total: subtotal + tax };
}
